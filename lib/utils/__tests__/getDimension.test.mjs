import { it } from 'node:test';

import getDimension from '../getDimension.mjs';
import valueParser from 'postcss-value-parser';

it('getDimension', (t) => {
	t.assert.strictEqual(getDimension().number, null);
	t.assert.strictEqual(getDimension().unit, null);
	t.assert.strictEqual(getDimension({}).number, null);
	t.assert.strictEqual(getDimension({}).unit, null);

	// testing Dimension.unit
	t.assert.strictEqual(getDimension(valueParser('1.1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('1.1000s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('1.1S').nodes[0]).unit, 'S');
	t.assert.strictEqual(getDimension(valueParser('+1.1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('+1.1000s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('-1.1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('-1.1000s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('1.1e10s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('+1.1e10s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('-1.1e10s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('1.1e+10s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('1.1e-10s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('+1.1e+10s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('+1.1e-10s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('-1.1e-10s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('-1.1e+10s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('1px').nodes[0]).unit, 'px');
	t.assert.strictEqual(getDimension(valueParser('1pX').nodes[0]).unit, 'pX');
	t.assert.strictEqual(getDimension(valueParser('1PX').nodes[0]).unit, 'PX');
	t.assert.strictEqual(getDimension(valueParser('+1px').nodes[0]).unit, 'px');
	t.assert.strictEqual(getDimension(valueParser('-1px').nodes[0]).unit, 'px');
	t.assert.strictEqual(getDimension(valueParser('1e1px').nodes[0]).unit, 'px');
	t.assert.strictEqual(getDimension(valueParser('+1e1px').nodes[0]).unit, 'px');
	t.assert.strictEqual(getDimension(valueParser('-1e1px').nodes[0]).unit, 'px');
	t.assert.strictEqual(getDimension(valueParser('1e-1px').nodes[0]).unit, 'px');
	t.assert.strictEqual(getDimension(valueParser('1e+1px').nodes[0]).unit, 'px');
	t.assert.strictEqual(getDimension(valueParser('+1e+1px').nodes[0]).unit, 'px');
	t.assert.strictEqual(getDimension(valueParser('+1e-1px').nodes[0]).unit, 'px');
	t.assert.strictEqual(getDimension(valueParser('-1e-1px').nodes[0]).unit, 'px');
	t.assert.strictEqual(getDimension(valueParser('-1e+1px').nodes[0]).unit, 'px');
	t.assert.strictEqual(getDimension(valueParser('.1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('+.1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('-.1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('+.1000s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('-.1000s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('.1e1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('+.1e1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('-.1e1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('.1e-1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('.1e+1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('+.1e+1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('+.1e-1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('-.1e-1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('-.1e+1s').nodes[0]).unit, 's');
	t.assert.strictEqual(getDimension(valueParser('100%').nodes[0]).unit, '%');
	t.assert.strictEqual(getDimension(valueParser('100').nodes[0]).unit, '');
	t.assert.strictEqual(getDimension(valueParser('0\\0').nodes[0]).unit, '');
	t.assert.strictEqual(getDimension(valueParser('10px\\9').nodes[0]).unit, 'px');
	t.assert.strictEqual(getDimension(valueParser('6e-2px').nodes[0]).unit, 'px');
	t.assert.strictEqual(getDimension(valueParser('.0').nodes[0]).unit, '');
	t.assert.strictEqual(getDimension(valueParser('+.0').nodes[0]).unit, '');
	t.assert.strictEqual(getDimension(valueParser('-.0').nodes[0]).unit, '');
	t.assert.strictEqual(getDimension(valueParser('.0e1').nodes[0]).unit, '');
	t.assert.strictEqual(getDimension(valueParser('+.0e1').nodes[0]).unit, '');
	t.assert.strictEqual(getDimension(valueParser('-.0e1').nodes[0]).unit, '');

	// testing Dimension.number
	t.assert.strictEqual(getDimension(valueParser('1.1s').nodes[0]).number, '1.1');
	t.assert.strictEqual(getDimension(valueParser('1.1000s').nodes[0]).number, '1.1000');
	t.assert.strictEqual(getDimension(valueParser('1.1S').nodes[0]).number, '1.1');
	t.assert.strictEqual(getDimension(valueParser('+1.1s').nodes[0]).number, '+1.1');
	t.assert.strictEqual(getDimension(valueParser('+1.1000s').nodes[0]).number, '+1.1000');
	t.assert.strictEqual(getDimension(valueParser('-1.1s').nodes[0]).number, '-1.1');
	t.assert.strictEqual(getDimension(valueParser('-1.1000s').nodes[0]).number, '-1.1000');
	t.assert.strictEqual(getDimension(valueParser('1.1e10s').nodes[0]).number, '1.1e10');
	t.assert.strictEqual(getDimension(valueParser('+1.1e10s').nodes[0]).number, '+1.1e10');
	t.assert.strictEqual(getDimension(valueParser('-1.1e10s').nodes[0]).number, '-1.1e10');
	t.assert.strictEqual(getDimension(valueParser('1.1e+10s').nodes[0]).number, '1.1e+10');
	t.assert.strictEqual(getDimension(valueParser('1.1e-10s').nodes[0]).number, '1.1e-10');
	t.assert.strictEqual(getDimension(valueParser('+1.1e+10s').nodes[0]).number, '+1.1e+10');
	t.assert.strictEqual(getDimension(valueParser('+1.1e-10s').nodes[0]).number, '+1.1e-10');
	t.assert.strictEqual(getDimension(valueParser('-1.1e-10s').nodes[0]).number, '-1.1e-10');
	t.assert.strictEqual(getDimension(valueParser('-1.1e+10s').nodes[0]).number, '-1.1e+10');
	t.assert.strictEqual(getDimension(valueParser('1px').nodes[0]).number, '1');
	t.assert.strictEqual(getDimension(valueParser('1pX').nodes[0]).number, '1');
	t.assert.strictEqual(getDimension(valueParser('1PX').nodes[0]).number, '1');
	t.assert.strictEqual(getDimension(valueParser('+1px').nodes[0]).number, '+1');
	t.assert.strictEqual(getDimension(valueParser('-1px').nodes[0]).number, '-1');
	t.assert.strictEqual(getDimension(valueParser('1e1px').nodes[0]).number, '1e1');
	t.assert.strictEqual(getDimension(valueParser('+1e1px').nodes[0]).number, '+1e1');
	t.assert.strictEqual(getDimension(valueParser('-1e1px').nodes[0]).number, '-1e1');
	t.assert.strictEqual(getDimension(valueParser('1e-1px').nodes[0]).number, '1e-1');
	t.assert.strictEqual(getDimension(valueParser('1e+1px').nodes[0]).number, '1e+1');
	t.assert.strictEqual(getDimension(valueParser('+1e+1px').nodes[0]).number, '+1e+1');
	t.assert.strictEqual(getDimension(valueParser('+1e-1px').nodes[0]).number, '+1e-1');
	t.assert.strictEqual(getDimension(valueParser('-1e-1px').nodes[0]).number, '-1e-1');
	t.assert.strictEqual(getDimension(valueParser('-1e+1px').nodes[0]).number, '-1e+1');
	t.assert.strictEqual(getDimension(valueParser('.1s').nodes[0]).number, '.1');
	t.assert.strictEqual(getDimension(valueParser('+.1s').nodes[0]).number, '+.1');
	t.assert.strictEqual(getDimension(valueParser('-.1s').nodes[0]).number, '-.1');
	t.assert.strictEqual(getDimension(valueParser('+.1000s').nodes[0]).number, '+.1000');
	t.assert.strictEqual(getDimension(valueParser('-.1000s').nodes[0]).number, '-.1000');
	t.assert.strictEqual(getDimension(valueParser('.1e1s').nodes[0]).number, '.1e1');
	t.assert.strictEqual(getDimension(valueParser('+.1e1s').nodes[0]).number, '+.1e1');
	t.assert.strictEqual(getDimension(valueParser('-.1e1s').nodes[0]).number, '-.1e1');
	t.assert.strictEqual(getDimension(valueParser('.1e-1s').nodes[0]).number, '.1e-1');
	t.assert.strictEqual(getDimension(valueParser('.1e+1s').nodes[0]).number, '.1e+1');
	t.assert.strictEqual(getDimension(valueParser('+.1e+1s').nodes[0]).number, '+.1e+1');
	t.assert.strictEqual(getDimension(valueParser('+.1e-1s').nodes[0]).number, '+.1e-1');
	t.assert.strictEqual(getDimension(valueParser('-.1e-1s').nodes[0]).number, '-.1e-1');
	t.assert.strictEqual(getDimension(valueParser('-.1e+1s').nodes[0]).number, '-.1e+1');
	t.assert.strictEqual(getDimension(valueParser('100%').nodes[0]).number, '100');
	t.assert.strictEqual(getDimension(valueParser('100').nodes[0]).number, '100');
	t.assert.strictEqual(getDimension(valueParser('0\\0').nodes[0]).number, '0');
	t.assert.strictEqual(getDimension(valueParser('10px\\9').nodes[0]).number, '10');
	t.assert.strictEqual(getDimension(valueParser('6e-2px').nodes[0]).number, '6e-2');
	t.assert.strictEqual(getDimension(valueParser('.0').nodes[0]).number, '.0');
	t.assert.strictEqual(getDimension(valueParser('+.0').nodes[0]).number, '+.0');
	t.assert.strictEqual(getDimension(valueParser('-.0').nodes[0]).number, '-.0');
	t.assert.strictEqual(getDimension(valueParser('.0e1').nodes[0]).number, '.0e1');
	t.assert.strictEqual(getDimension(valueParser('+.0e1').nodes[0]).number, '+.0e1');
	t.assert.strictEqual(getDimension(valueParser('-.0e1').nodes[0]).number, '-.0e1');

	// testing invalid inputs
	t.assert.strictEqual(getDimension(valueParser('#fff').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('#000').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('#zzzzzz').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('#F').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('#PX').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('"100"').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('"100px"').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser(' ').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('/').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('+').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('word').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('px').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('url()').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('url()px').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('$variable').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('${$variable}').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('${$variable}px').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('${$variable}px').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('@variable').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('e1').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('wordPX').nodes[0]).unit, null);
	t.assert.strictEqual(getDimension(valueParser('..0').nodes[0]).unit, null);

	t.assert.strictEqual(getDimension(valueParser('#fff').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('#000').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('#zzzzzz').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('#F').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('#PX').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('"100"').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('"100px"').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser(' ').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('/').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('+').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('word').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('px').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('url()').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('url()px').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('$variable').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('${$variable}').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('${$variable}px').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('${$variable}px').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('@variable').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('e1').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('wordPX').nodes[0]).number, null);
	t.assert.strictEqual(getDimension(valueParser('..0').nodes[0]).number, null);
});
